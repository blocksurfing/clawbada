/**
 * Encode the website's own sound effects (UI sounds outside the Unity battle) into the web app as content-hashed AAC,
 * and generate the lookup React imports — the same shape as build-music.ts.
 *
 *   bun scripts/build-sfx.ts                  # masters from audio-masters/sfx/
 *   bun scripts/build-sfx.ts --in <dir>       # elsewhere
 *
 * Masters are named like the battle's (`SFX_UI_<Name>[_<Part>].wav`, 48 kHz/16-bit); each becomes
 * `public/audio/sfx/SFX_UI_<Name>.<hash>.m4a` and a camelCase key in lib/site-sfx.generated.ts
 * (SFX_UI_Sidebar_Open → sidebarOpen). The masters folder is not in git (.gitignore audio-masters/); the built files are.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

const args = process.argv.slice(2);
const opt = (k: string, d: string) => { const i = args.indexOf(`--${k}`); return i >= 0 ? args[i + 1] : d; };
const root = resolve(import.meta.dir, '..');
const inDir = resolve(opt('in', join(root, 'audio-masters/sfx')));
const bitrate = opt('bitrate', '128k');
const outDir = join(root, 'apps/web/public/audio/sfx');
const genPath = join(root, 'apps/web/src/lib/site-sfx.generated.ts');
const MASTER = /^SFX_UI_[A-Za-z0-9]+(_[A-Za-z0-9]+)*\.wav$/;
const BUILT = /^SFX_UI_[A-Za-z0-9_]+\.[0-9a-f]{8}\.m4a$/;
/** Level trims (dB) applied while encoding, so every UI sound sits at one level whatever the master. The Shell's rock
 *  presses arrive ~8–10 dB hotter (−13 dB mean) than the wheel (−21/−23) — trimmed to sit with it (owner 2026-10-26). */
const GAIN_DB: Record<string, number> = { SFX_UI_Rock_01: -8, SFX_UI_Rock_02: -8, SFX_UI_Rock_03: -8 };
/** A built sound averaging below this is a mastering mistake: stop instead of shipping silence. */
const MIN_MEAN_DB = -45;

/** SFX_UI_Sidebar_Open → sidebarOpen */
export function sfxKey(stem: string): string {
  const parts = stem.replace(/^SFX_UI_/, '').split('_');
  return parts.map((p, i) => (i === 0 ? p.charAt(0).toLowerCase() + p.slice(1) : p.charAt(0).toUpperCase() + p.slice(1))).join('');
}

if (import.meta.main) {
  mkdirSync(outDir, { recursive: true });
  const masters = existsSync(inDir) ? readdirSync(inDir).filter((f) => MASTER.test(f)).sort() : [];
  if (masters.length === 0) { console.error(`no SFX_UI_*.wav masters in ${inDir}`); process.exit(1); }
  const urls: Record<string, string> = {};
  const keep = new Set<string>();
  for (const file of masters) {
    const stem = basename(file, '.wav');
    const tmp = join(outDir, `.${stem}.tmp.m4a`);
    const gain = GAIN_DB[stem] ?? 0;
    const enc = (codec: string) => Bun.spawnSync(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', join(inDir, file),
      '-vn', ...(gain ? ['-af', `volume=${gain}dB`] : []), '-c:a', codec, '-b:a', bitrate, '-movflags', '+faststart', tmp]);
    let r = enc('aac_at');
    if (r.exitCode !== 0) r = enc('aac');
    if (r.exitCode !== 0) { console.error(`ffmpeg failed for ${file}:\n${new TextDecoder().decode(r.stderr)}`); process.exit(1); }
    const level = new TextDecoder().decode(Bun.spawnSync(['ffmpeg', '-hide_banner', '-nostats', '-i', tmp, '-af', 'volumedetect', '-f', 'null', '-']).stderr);
    const mean = Number(/mean_volume: (-?[\d.]+) dB/.exec(level)?.[1] ?? NaN), peak = Number(/max_volume: (-?[\d.]+) dB/.exec(level)?.[1] ?? NaN);
    if (!(mean >= MIN_MEAN_DB)) { console.error(`${file}: built sound averages ${mean} dB (peak ${peak} dB) — below ${MIN_MEAN_DB} dB. Fix the master.`); process.exit(1); }
    const bytes = readFileSync(tmp);
    const name = `${stem}.${createHash('sha256').update(bytes).digest('hex').slice(0, 8)}.m4a`;
    rmSync(join(outDir, name), { force: true });
    Bun.spawnSync(['mv', tmp, join(outDir, name)]);
    keep.add(name);
    urls[sfxKey(stem)] = `/audio/sfx/${name}`;
    console.log(`${file} → ${name}  ${(bytes.length / 1024).toFixed(0)} KB, mean ${mean} dB / peak ${peak} dB${gain ? ` (${gain} dB trim)` : ''}`);
  }
  for (const f of readdirSync(outDir)) if (BUILT.test(f) && !keep.has(f)) { rmSync(join(outDir, f)); console.log(`removed stale ${f}`); }
  const keys = Object.keys(urls).sort();
  writeFileSync(genPath, `// GENERATED by scripts/build-sfx.ts — do not edit. Re-run after changing a master in audio-masters/sfx/.
export type SiteSfx = ${keys.map((k) => `'${k}'`).join(' | ')};
/** Content-hashed URLs, served immutable from public/audio/sfx/ (lib/site-sfx.ts plays them). */
export const SITE_SFX: Record<SiteSfx, string> = {
${keys.map((k) => `  ${k}: ${JSON.stringify(urls[k])},`).join('\n')}
};
`);
  console.log(`wrote ${genPath.replace(root + '/', '')}`);
}
